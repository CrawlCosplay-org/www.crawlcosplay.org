<h3>5. Master the Identification Minigame</h3> 
<p><b>Consumable items</b> in DCSS are initially unidentified.</p>
<p>Learning how to identify items efficiently can give you access to useful resources earlier.</p>

<ul>
<li>Begin by blind-reading your early 2-stacks of scrolls until you find the Scroll of Identification. You should do this at the very start of floor 2 while standing on the upstairs so you can retreat if necessary.</li>
<li>Use your Identifies on unknown potions (in stacks when possible), until you find the Potion of Curing. This counters poison, one of the major killers in the early game.</li>
<li>Use subsequent Identify scrolls on scrolls until you find Scrolls of Teleport and Blink.</li>
<li>Continue blind-reading your 2 stacks of scrolls in this manner through the game.</li>
<li>Buy cheap identified consumables you don't know yet from shops to make the process faster (even bad items like moonshine to remove them from the 'unknowns' pool).</li>
</ul>

