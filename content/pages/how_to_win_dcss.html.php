<br>

<h3>6. Learn From Your Deaths</h3>
<p>Early on, you're going to die. A lot.</p>

<p>After a death, ask yourself:</p>

<ul>
<li>What actually killed me?</li>
<li>When did the situation become dangerous?</li>
<li>Could I have escaped?</li>
<li>Did I choose to fight when I could have walked away?</li>
<li>Did I understand what the monster could do before taking the fight?</li>
</ul>

<p>Every death is an opportunity to learn something that can keep your next character alive. Usually, you can take one of the above questions and use it to survive that scenario next time.</p>

<br>

<h3>7. Get Your First Win</h3>
<p>Your first win doesn't require perfect knowledge of DCSS. It just requires putting together enough good decisions to survive all the way to the end.</p>

<p>Once you've won, you'll have a much better understanding of how the game works and can start experimenting with more unusual characters and strategies.</p>
<p>Choose a character that lets you concentrate on learning the fundamentals of DCSS, work on seeing more of the game more often, and you'll solve the puzzle before you know it!</p>

